export function getPart(partId) {
  return PARTS[partId];
}

export function partGeometry(part) {
  if (part.category === "engine") return { height: part.thrust > 150000 ? 1.35 : 1.05, width: 0.9 };
  if (part.category === "fuel") return { height: 0.85 + Math.min(1.2, Math.max(0.72, part.fuelMass / 3600)) * 0.78, width: 0.9 };
  if (part.category === "aero") return { height: 0.7, width: part.liftArea ? 3 : 1.5 };
  if (part.category === "structure") return { height: part.splitStage ? 0.65 : 0.55, width: 0.8 };
  if (part.category === "command") return { height: 1.25, width: 0.85 };
  return { height: 0.65, width: 0.8 };
}

export const ASSEMBLY_LIMITS = { engineOffset: 0.7, engineAngle: 15, finTravel: 1.2 };

export function getContract(contractId) {
  return CONTRACTS.find((contract) => contract.id === contractId);
}

export function getTechNode(nodeId) {
  return TECH_NODES.find((node) => node.id === nodeId);
}

export function isPartUnlocked(partId, unlockedTech) {
  return TECH_NODES.some(
    (node) => unlockedTech.includes(node.id) && node.parts.includes(partId),
  );
}

export function requiredTechForPart(partId) {
  return TECH_NODES.find((node) => node.parts.includes(partId));
}
